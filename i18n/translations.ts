export function detectLanguageFromLocation(locationText: string): SupportedLanguage {
  if (!locationText) return "en";
  const lower = locationText.toLowerCase();

  for (const lang of LANGUAGES) {
    for (const state of lang.states) {
      if (lower.includes(state)) {
        return lang.code;
      }
    }
  }
  return "en";
}

